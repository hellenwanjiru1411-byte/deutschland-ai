const BASE = new URL("../", import.meta.url).pathname;
if (!process.env.DATABASE_URL) {
  console.error("upload-hardening-check: DATABASE_URL is not set — nothing to check against.");
  process.exit(1);
}

const sharp = (await import("sharp")).default;
const { sql } = await import(`${BASE}src/db.ts`);
const uploads = await import(`${BASE}src/server/uploads.server.ts`);
const data = await import(`${BASE}src/server/data.server.ts`);
const access = await import(`${BASE}src/server/access.server.ts`);
const { saveRequestUnderPilotRules } = await import(`${BASE}src/server/pilot.server.ts`);

const q = sql();
let total = 0;
let failures = 0;
function check(name, passed, detail) {
  total += 1;
  console.log(`${passed ? "PASS" : "FAIL"}  ${name}${detail ? ` — ${detail}` : ""}`);
  if (!passed) failures += 1;
}

/* ------------------------------------------------------------ test fixtures */

/** A small JPEG made by us, so the test does not depend on a file on disk. */
async function plainJpeg() {
  return sharp({
    create: { width: 24, height: 16, channels: 3, background: { r: 12, g: 60, b: 40 } },
  })
    .jpeg({ quality: 90 })
    .toBuffer();
}

/**
 * A REAL APP1/EXIF block carrying GPS coordinates, built here byte by byte so the
 * test does not depend on a library's idea of EXIF: a TIFF header, one IFD0 with
 * ImageDescription + Make and a GPS pointer, and a GPS IFD with the latitude and
 * longitude of Berlin as rationals. The description also spells the coordinates
 * out, so a plain byte search for them is a fair test.
 */
function gpsExifApp1() {
  const desc = "GPS:52.5200N,13.4050E\0";
  const make = "TestCamera\0";
  const ifd0Offset = 8;
  const ifd0Size = 2 + 3 * 12 + 4;
  const gpsOffset = ifd0Offset + ifd0Size;
  const gpsSize = 2 + 4 * 12 + 4;
  const descOff = gpsOffset + gpsSize;
  const makeOff = descOff + desc.length;
  const latOff = makeOff + make.length;
  const lonOff = latOff + 24;
  const tiff = Buffer.alloc(lonOff + 24);

  tiff.write("II", 0, "latin1"); // little endian
  tiff.writeUInt16LE(0x2a, 2);
  tiff.writeUInt32LE(ifd0Offset, 4);

  let p = ifd0Offset;
  tiff.writeUInt16LE(3, p);
  p += 2;
  tiff.writeUInt16LE(0x010e, p); // ImageDescription
  tiff.writeUInt16LE(2, p + 2);
  tiff.writeUInt32LE(desc.length, p + 4);
  tiff.writeUInt32LE(descOff, p + 8);
  p += 12;
  tiff.writeUInt16LE(0x010f, p); // Make
  tiff.writeUInt16LE(2, p + 2);
  tiff.writeUInt32LE(make.length, p + 4);
  tiff.writeUInt32LE(makeOff, p + 8);
  p += 12;
  tiff.writeUInt16LE(0x8825, p); // GPSInfoIFDPointer
  tiff.writeUInt16LE(4, p + 2);
  tiff.writeUInt32LE(1, p + 4);
  tiff.writeUInt32LE(gpsOffset, p + 8);
  p += 12;
  tiff.writeUInt32LE(0, p); // no next IFD

  p = gpsOffset;
  tiff.writeUInt16LE(4, p);
  p += 2;
  tiff.writeUInt16LE(0x0001, p); // GPSLatitudeRef = "N"
  tiff.writeUInt16LE(2, p + 2);
  tiff.writeUInt32LE(2, p + 4);
  tiff.write("N\0", p + 8, "latin1");
  p += 12;
  tiff.writeUInt16LE(0x0002, p); // GPSLatitude
  tiff.writeUInt16LE(5, p + 2);
  tiff.writeUInt32LE(3, p + 4);
  tiff.writeUInt32LE(latOff, p + 8);
  p += 12;
  tiff.writeUInt16LE(0x0003, p); // GPSLongitudeRef = "E"
  tiff.writeUInt16LE(2, p + 2);
  tiff.writeUInt32LE(2, p + 4);
  tiff.write("E\0", p + 8, "latin1");
  p += 12;
  tiff.writeUInt16LE(0x0004, p); // GPSLongitude
  tiff.writeUInt16LE(5, p + 2);
  tiff.writeUInt32LE(3, p + 4);
  tiff.writeUInt32LE(lonOff, p + 8);
  p += 12;
  tiff.writeUInt32LE(0, p);

  tiff.write(desc, descOff, "latin1");
  tiff.write(make, makeOff, "latin1");
  const rational = (num, den) => {
    const b = Buffer.alloc(8);
    b.writeUInt32LE(num, 0);
    b.writeUInt32LE(den, 4);
    return b;
  };
  rational(52, 1).copy(tiff, latOff);
  rational(31, 1).copy(tiff, latOff + 8);
  rational(1200, 100).copy(tiff, latOff + 16);
  rational(13, 1).copy(tiff, lonOff);
  rational(24, 1).copy(tiff, lonOff + 8);
  rational(1800, 100).copy(tiff, lonOff + 16);

  const payload = Buffer.concat([Buffer.from("Exif\0\0", "latin1"), tiff]);
  const marker = Buffer.alloc(4);
  marker[0] = 0xff;
  marker[1] = 0xe1; // APP1
  marker.writeUInt16BE(payload.length + 2, 2);
  return Buffer.concat([marker, payload]);
}

/** A JPEG with the GPS EXIF block inserted right after the start-of-image marker. */
async function jpegWithGpsExif() {
  const jpeg = await plainJpeg();
  return Buffer.concat([
    jpeg.subarray(0, 2),
    gpsExifApp1(),
    jpeg.subarray(2),
    Buffer.from("PAYLOAD-AFTER-EOI", "latin1"),
  ]);
}

async function pngWithTrailingPayload() {
  const png = await sharp({
    create: { width: 20, height: 12, channels: 3, background: { r: 200, g: 180, b: 60 } },
  })
    .png()
    .toBuffer();
  return Buffer.concat([png, Buffer.from("SECRET-PAYLOAD-AFTER-IEND", "latin1")]);
}

/** A whole, tiny PDF: header, one object, trailer, end marker. */
function pdfOfSize(bytes) {
  const head = "%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\ntrailer<</Root 1 0 R>>\n";
  const tail = "%%EOF\n";
  const filler = Buffer.alloc(Math.max(0, bytes - head.length - tail.length), 0x20);
  return Buffer.concat([Buffer.from(head, "latin1"), filler, Buffer.from(tail, "latin1")]);
}

const asIncoming = (bytes, filename, mimeType) => ({
  filename,
  mimeType,
  size: bytes.length,
  contentBase64: bytes.toString("base64"),
});

const contains = (bytes, text) =>
  Buffer.from(bytes).toString("latin1").includes(text);

/* ------------------------------------------------------- the attempts, one by one */

const svg = Buffer.from(
  '<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>',
  "latin1",
);
const svgAttempt = await uploads.prepareDocuments([asIncoming(svg, "rechnung.png", "image/png")]);
check(
  "an SVG renamed to .png and declared image/png is REFUSED",
  !svgAttempt.ok && svgAttempt.code === "type",
  `code=${svgAttempt.ok ? "accepted!" : svgAttempt.code}`,
);

const elf = Buffer.concat([
  Buffer.from([0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00]), // \x7fELF
  Buffer.alloc(200, 0x00),
]);
const elfAttempt = await uploads.prepareDocuments([asIncoming(elf, "antrag.pdf", "application/pdf")]);
check(
  "an executable (ELF) renamed to .pdf is REFUSED",
  !elfAttempt.ok && elfAttempt.code === "type",
  `code=${elfAttempt.ok ? "accepted!" : elfAttempt.code}`,
);

const text = Buffer.from("Liebe Frau Muster, hiermit beantrage ich ...", "utf8");
const textAttempt = await uploads.prepareDocuments([asIncoming(text, "brief.jpg", "image/jpeg")]);
check(
  "a text file renamed to .jpg is REFUSED",
  !textAttempt.ok && textAttempt.code === "type",
  `code=${textAttempt.ok ? "accepted!" : textAttempt.code}`,
);

const tooBig = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(2 * 1024 * 1024)]);
const tooBigAttempt = await uploads.prepareDocuments([
  asIncoming(tooBig, "gross.png", "image/png"),
]);
check(
  "a file over the 2 MB per-file cap is REFUSED (measured on the decoded bytes)",
  !tooBigAttempt.ok && tooBigAttempt.code === "too_large",
  `code=${tooBigAttempt.ok ? "accepted!" : tooBigAttempt.code}, bytes=${tooBig.length}`,
);

const big1 = pdfOfSize(1_600_000);
const big2 = pdfOfSize(1_600_000);
const totalAttempt = await uploads.prepareDocuments([
  asIncoming(big1, "a.pdf", "application/pdf"),
  asIncoming(big2, "b.pdf", "application/pdf"),
]);
check(
  "two files that each fit but together pass the 3 MB total cap are REFUSED",
  !totalAttempt.ok && totalAttempt.code === "total_too_large",
  `code=${totalAttempt.ok ? "accepted!" : totalAttempt.code}, total=${big1.length + big2.length}`,
);

const manyAttempt = await uploads.prepareDocuments([
  asIncoming(pdfOfSize(500), "a.pdf", "application/pdf"),
  asIncoming(pdfOfSize(500), "b.pdf", "application/pdf"),
  asIncoming(pdfOfSize(500), "c.pdf", "application/pdf"),
]);
check(
  "three files are REFUSED (at most 2)",
  !manyAttempt.ok && manyAttempt.code === "too_many",
  `code=${manyAttempt.ok ? "accepted!" : manyAttempt.code}`,
);

/* ---------------------------------------------------- the JPEG with GPS EXIF */

const gpsJpeg = await jpegWithGpsExif();
const uploadedBytes = gpsJpeg;
const gpsAttempt = await uploads.prepareDocuments([
  asIncoming(gpsJpeg, "foto vom brief.jpg", "image/jpeg"),
]);
check(
  "a valid JPEG carrying GPS EXIF is ACCEPTED",
  gpsAttempt.ok,
  gpsAttempt.ok ? `stored ${gpsAttempt.documents[0].size} bytes` : `code=${gpsAttempt.code}`,
);

if (gpsAttempt.ok) {
  const stored = Buffer.from(gpsAttempt.documents[0].contentBase64, "base64");
  check(
    "the UPLOADED bytes really did carry the EXIF block (test is not vacuous)",
    contains(uploadedBytes, "Exif") &&
      contains(uploadedBytes, "GPS:52.5200N,13.4050E") &&
      contains(uploadedBytes, "TestCamera"),
    `uploaded ${uploadedBytes.length} bytes`,
  );
  check(
    "the STORED bytes contain no 'Exif' marker",
    !contains(stored, "Exif"),
    `stored ${stored.length} bytes`,
  );
  check(
    "the STORED bytes contain no GPS coordinates",
    !contains(stored, "GPS:52.5200N,13.4050E") && !contains(stored, "GPSLatitude"),
    "searched the whole stored file",
  );
  check(
    "the STORED bytes contain no camera name and nothing appended after the image",
    !contains(stored, "TestCamera") && !contains(stored, "PAYLOAD-AFTER-EOI"),
    "searched the whole stored file",
  );
  const meta = await sharp(stored).metadata();
  check(
    "sharp reads no EXIF from the stored file",
    meta.exif === undefined,
    `format=${meta.format}, exif=${meta.exif === undefined ? "absent" : "present"}`,
  );
  check(
    "the stored file is still a working JPEG of the same picture",
    meta.format === "jpeg" && meta.width === 24 && meta.height === 16,
    `${meta.width}x${meta.height}`,
  );
  const name = gpsAttempt.documents[0].filename;
  check(
    "the stored filename is generated by us, not the person's",
    /^[0-9a-f-]{36}\.jpg$/.test(name),
    `stored=${name}, shown=${gpsAttempt.documents[0].originalName}`,
  );
  check(
    "the person's own name is kept only as a display label",
    gpsAttempt.documents[0].originalName === "foto vom brief.jpg",
    gpsAttempt.documents[0].originalName,
  );
}

/* ------------------------------------------------------------- PNG and PDF */

const pngBytes = await pngWithTrailingPayload();
const pngAttempt = await uploads.prepareDocuments([asIncoming(pngBytes, "scan.png", "image/png")]);
const pngStored = pngAttempt.ok ? Buffer.from(pngAttempt.documents[0].contentBase64, "base64") : Buffer.alloc(0);
check(
  "a PNG with data appended after its end is ACCEPTED and the appended data is gone",
  pngAttempt.ok && contains(pngBytes, "SECRET-PAYLOAD-AFTER-IEND") && !contains(pngStored, "SECRET-PAYLOAD-AFTER-IEND"),
  pngAttempt.ok ? `uploaded ${pngBytes.length} → stored ${pngStored.length}` : `code=${pngAttempt.code}`,
);

const pdfBytes = pdfOfSize(2048);
const pdfAttempt = await uploads.prepareDocuments([asIncoming(pdfBytes, "bescheid.pdf", "application/pdf")]);
check(
  "a valid PDF is ACCEPTED as application/pdf with a .pdf name",
  pdfAttempt.ok &&
    pdfAttempt.documents[0].mimeType === "application/pdf" &&
    /^[0-9a-f-]{36}\.pdf$/.test(pdfAttempt.documents[0].filename),
  pdfAttempt.ok ? pdfAttempt.documents[0].mimeType : `code=${pdfAttempt.code}`,
);

const lyingAttempt = await uploads.prepareDocuments([
  asIncoming(await plainJpeg(), "bild.pdf", "application/pdf"),
]);
check(
  "a JPEG that DECLARES application/pdf is stored as image/jpeg (the bytes win)",
  lyingAttempt.ok && lyingAttempt.documents[0].mimeType === "image/jpeg",
  lyingAttempt.ok ? lyingAttempt.documents[0].mimeType : `code=${lyingAttempt.code}`,
);

const traversalAttempt = await uploads.prepareDocuments([
  asIncoming(pdfBytes, "../../etc/passwd", "application/pdf"),
]);
check(
  "a filename with path segments cannot become the stored name",
  traversalAttempt.ok &&
    /^[0-9a-f-]{36}\.pdf$/.test(traversalAttempt.documents[0].filename) &&
    !traversalAttempt.documents[0].originalName.includes("/"),
  traversalAttempt.ok ? `stored=${traversalAttempt.documents[0].filename}, shown=${traversalAttempt.documents[0].originalName}` : `code=${traversalAttempt.code}`,
);

/* ---------------------------------------------------- round trip through Neon */

const stamp = Date.now();
const ownerEmail = `dai-test-upload-${stamp}@example.com`;
const otherEmail = `dai-test-upload-other-${stamp}@example.com`;
let ownerId = null;
let otherId = null;
let requestId = null;

async function cleanup() {
  try {
    await q`delete from documents where request_id in (select id from requests where user_id in (select id from users where email_norm like 'dai-test-upload-%'))`;
    await q`delete from requests where user_id in (select id from users where email_norm like 'dai-test-upload-%')`;
    await q`delete from sessions where user_id in (select id from users where email_norm like 'dai-test-upload-%')`;
    await q`delete from users where email_norm like 'dai-test-upload-%'`;
    await q`delete from login_attempts where email_norm like 'dai-test-upload-%'`;
  } catch (error) {
    console.error("cleanup failed:", error instanceof Error ? error.message : "unknown");
  }
}

try {
  const owner = await data.createUser({ name: "Upload Check", email: ownerEmail, password: "test-password-1" });
  const other = await data.createUser({ name: "Upload Other", email: otherEmail, password: "test-password-2" });
  if (!owner.ok || !other.ok) throw new Error("could not create the throwaway users");
  ownerId = owner.user.id;
  otherId = other.user.id;

  const prepared = await uploads.prepareDocuments([
    asIncoming(gpsJpeg, "foto vom brief.jpg", "image/jpeg"),
    asIncoming(pdfBytes, "bescheid.pdf", "application/pdf"),
  ]);
  if (!prepared.ok) throw new Error(`prepare refused the valid pair: ${prepared.code}`);

  const saved = await saveRequestUnderPilotRules({
    userId: ownerId,
    city: "Berlin",
    state: "Berlin",
    subject: "anmeldung",
    message: "Upload hardening check — this row is deleted at the end of the run.",
    phone: null,
    documents: prepared.documents.map((doc) => ({ ...doc, aiMetered: false })),
    readingAidAck: true,
    locale: "de",
  });
  if (!saved.ok) throw new Error(`the write path refused: ${saved.code}`);
  requestId = saved.id;

  const rows = await q`select id, filename, original_name, mime_type, size, content_base64
                       from documents where request_id = ${requestId} order by created_at asc`;
  check(
    "the database holds both documents, with our generated names and the real sizes",
    rows.length === 2 &&
      rows.every((row) => /^[0-9a-f-]{36}\.(jpg|pdf)$/.test(String(row.filename))) &&
      rows.every((row) => Number(row.size) === Buffer.from(String(row.content_base64), "base64").length),
    `rows=${rows.length}`,
  );

  const imageRow = rows.find((row) => String(row.mime_type) === "image/jpeg");
  const storedImage = Buffer.from(String(imageRow.content_base64), "base64");
  check(
    "the JPEG stored in Postgres carries no EXIF and no GPS",
    !contains(storedImage, "Exif") &&
      !contains(storedImage, "GPS:52.5200N,13.4050E") &&
      !contains(storedImage, "PAYLOAD-AFTER-EOI"),
    `${storedImage.length} bytes read back from the database`,
  );

  const viaAccess = await access.getDocumentForDownload(
    access.viewerForUser({ id: ownerId }),
    String(imageRow.id),
  );
  check(
    "the owner reads the same rebuilt bytes back through the access module",
    viaAccess !== null &&
      Buffer.from(viaAccess.contentBase64, "base64").equals(storedImage) &&
      viaAccess.mimeType === "image/jpeg",
    viaAccess ? `${viaAccess.size} bytes` : "not found",
  );

  const asOther = await access.getDocumentForDownload(
    access.viewerForUser({ id: otherId }),
    String(imageRow.id),
  );
  check(
    "another signed-in person cannot read that document at all",
    asOther === null,
    asOther === null ? "not found (as it must be)" : "LEAK",
  );

  const headers = uploads.documentResponseHeaders({
    filename: String(imageRow.filename),
    mimeType: String(imageRow.mime_type),
  });
  check(
    "the serving headers pin the type, force a download and forbid sniffing",
    headers["Content-Type"] === "image/jpeg" &&
      headers["Content-Disposition"] === `attachment; filename="${String(imageRow.filename)}"` &&
      headers["X-Content-Type-Options"] === "nosniff",
    `${headers["Content-Type"]} · ${headers["Content-Disposition"]} · nosniff`,
  );

  const aid = await q`select reading_aid_version, reading_aid_locale, reading_aid_confirmed_at
                      from requests where id = ${requestId}`;
  check(
    "the reading-aid acknowledgement was recorded with the request",
    aid.length === 1 &&
      aid[0].reading_aid_version !== null &&
      aid[0].reading_aid_locale === "de" &&
      aid[0].reading_aid_confirmed_at !== null,
    `${String(aid[0]?.reading_aid_version)} / ${String(aid[0]?.reading_aid_locale)}`,
  );
} finally {
  await cleanup();
}

/* ------------------------------------------------------------------- counts */

// One literal query per table: the driver only accepts tagged templates, so the
// table name can never be a variable here.
const countRows = async () => ({
  users: Number((await q`select count(*)::int as n from users`)[0].n),
  sessions: Number((await q`select count(*)::int as n from sessions`)[0].n),
  requests: Number((await q`select count(*)::int as n from requests`)[0].n),
  documents: Number((await q`select count(*)::int as n from documents`)[0].n),
  login_attempts: Number((await q`select count(*)::int as n from login_attempts`)[0].n),
});
const counts = await countRows();
console.log(
  `\nrows left — users=${counts.users} sessions=${counts.sessions} requests=${counts.requests} documents=${counts.documents} login_attempts=${counts.login_attempts}`,
);
check(
  "every table is back at 0 after the run",
  Object.values(counts).every((n) => n === 0),
  JSON.stringify(counts),
);

console.log(
  failures === 0
    ? `\nall ${total} checks passed`
    : `\n${failures} of ${total} checks FAILED`,
);
process.exit(failures === 0 ? 0 : 1);
