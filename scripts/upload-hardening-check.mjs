/**
 * UPLOAD HARDENING CHECK — tries to get past the upload gate, and shows what
 * happened to every attempt.
 *
 * WHAT IT PROVES, against the REAL modules and the REAL database:
 *   - a file is accepted or refused by its first bytes, never by its name or by
 *     the type the browser declared,
 *   - an SVG renamed to `.png` is refused (an SVG is a script container),
 *   - an executable renamed to `.pdf` and a text file renamed to `.jpg` are refused,
 *   - the per-file cap and the per-submission total are measured on the real bytes,
 *   - a JPEG carrying EXIF with GPS coordinates is stored WITHOUT that block: the
 *     bytes we keep are rebuilt from the pixels, so EXIF, GPS and anything appended
 *     after the image are gone (proved by searching the stored bytes),
 *   - a PNG with data appended after its end is stored without that data,
 *   - the stored filename is generated by us, not the person's,
 *   - a document read back through the access module is the stored (rebuilt) file,
 *     and another user cannot read it at all.
 *
 * SAFETY: one throwaway user (prefix `dai-test-upload-`), everything it writes is
 * deleted before the final counts, and it never prints the connection string, a
 * document's content or an email address.
 *
 * Run from the site directory:  bun scripts/upload-hardening-check.mjs
 */
