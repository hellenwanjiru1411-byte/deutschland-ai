/**
 * UPLOAD HARDENING — the one place that decides whether an uploaded file is
 * stored, and in what shape.
 *
 * THE RULE: a file is judged by WHAT IT IS (its first bytes), never by what the
 * browser says it is. The declared MIME type and the filename are strings the
 * visitor's browser chooses — a renamed SVG arrives declaring `image/png`, and a
 * program arrives declaring `application/pdf`. Both are refused here because the
 * bytes do not match an allowed format.
 *
 * WHAT HAPPENS TO AN ACCEPTED FILE, IN ORDER:
 *   1. base64 is decoded; the real byte length is measured (the declared size is
 *      ignored entirely),
 *   2. the per-file cap and the per-submission total cap are checked on those
 *      real bytes,
 *   3. the format is decided by magic bytes: PDF (`%PDF-`), JPEG (`FF D8 FF`),
 *      PNG (`89 50 4E 47 0D 0A 1A 0A`). Nothing else is ever stored — which is
 *      what makes an SVG impossible here: an SVG is text/XML and matches none of
 *      the three, whatever it is called.
 *   4. an IMAGE is re-encoded from its pixels (sharp): every metadata block —
 *      EXIF, GPS, XMP, IPTC, comments — and anything appended after the image
 *      data is gone, because the stored bytes are new bytes produced from the
 *      decoded picture. EXIF orientation is applied first, so a phone photo does
 *      not come out sideways once its orientation tag is gone. If an image
 *      cannot be decoded and re-encoded, it is REFUSED — we fail closed rather
 *      than store bytes we could not rebuild.
 *   5. a PDF is NOT rewritten: its internals are not sanitised, it is stored as
 *      it arrived. It is served only as a download (`Content-Disposition:
 *      attachment`, pinned `application/pdf`, `nosniff`), never inline. That is
 *      the honest limit of this module — see the note at the bottom.
 *   6. the stored filename is generated by us (`<uuid>.<ext>`). The person's own
 *      filename is kept only as `original_name`, for display as text, and never
 *      becomes a path, a URL segment or a header value.
 *
 * WHAT THIS IS NOT: a sandbox. This app runs as one process, so there is no
 * separate quarantine container that opens a file before we keep it. The control
 * is deciding what the bytes are, before anything is written, plus rebuilding
 * every image from its pixels. Calling that a sandbox would be theatre, and the
 * codebase claims no such thing.
 *
 * CONFIDENTIALITY: nothing here logs. Refusals are codes; the caller turns them
 * into words in the visitor's language. No filename and no content ever reaches a
 * log line or an error message.
 */
import { randomUUID } from "node:crypto";

import { MAX_FILE_BYTES, MAX_FILES, MAX_TOTAL_BYTES } from "~/lib/constants";

/* ------------------------------------------------------------------- types */

/** The three formats this app stores. Decided by magic bytes, never by a header. */
export type FileKind = "pdf" | "jpeg" | "png";

/** What each kind is stored and served as. One table, so nothing can disagree. */
export const FILE_KINDS: Readonly<
  Record<FileKind, { mimeType: string; extension: string }>
> = {
  pdf: { mimeType: "application/pdf", extension: "pdf" },
  jpeg: { mimeType: "image/jpeg", extension: "jpg" },
  png: { mimeType: "image/png", extension: "png" },
};

/** Why a file was refused. A code — the caller translates it. */
export type UploadRefusal =
  | "too_many"
  | "too_large"
  | "total_too_large"
  | "type"
  | "unreadable";

/** What the browser sends. Only `filename` and `contentBase64` are believed, and the name only as a display label. */
export type IncomingFile = {
  filename: string;
  /** Ignored. Kept in the type because the browser sends it; never read as a decision. */
  mimeType?: string;
  /** Ignored. The real length is measured from the decoded bytes. */
  size?: number;
  contentBase64: string;
};

/** One file, ready to be written: our name, our type, our bytes. */
export type PreparedFile = {
  /** Generated by us. The only name that may become a path, a URL or a header. */
  filename: string;
  /** The person's own name, sanitised for display as text only. Never a header. */
  originalName: string;
  mimeType: string;
  /** The real length of the bytes below. */
  size: number;
  contentBase64: string;
  kind: FileKind;
  /** True when the stored bytes are a rebuild of an image, not the uploaded bytes. */
  reencoded: boolean;
};

export type PrepareResult =
  | { ok: true; documents: PreparedFile[] }
  | { ok: false; code: UploadRefusal };

/* ------------------------------------------------------------ magic bytes */

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
const JPEG_SIGNATURE = [0xff, 0xd8, 0xff];
const PDF_SIGNATURE = "%PDF-";

function startsWithBytes(bytes: Uint8Array, signature: readonly number[]): boolean {
  if (bytes.length < signature.length) return false;
  for (let i = 0; i < signature.length; i++) {
    if (bytes[i] !== signature[i]) return false;
  }
  return true;
}

/**
 * What IS this file? `null` for anything that is not a PDF, a JPEG or a PNG.
 *
 * PDF is the one format whose header may legally sit behind a little junk (the
 * spec tolerates bytes before `%PDF-`), so the marker is looked for in the first
 * kilobyte only. JPEG and PNG are fixed at offset 0.
 *
 * An SVG — however it is named and whatever type the browser declares — is text
 * starting with `<svg` or `<?xml`, so it matches none of the three and returns
 * `null`. That is the whole reason SVG can never be stored: not a blacklist that
 * could be worked around, but an allowlist of three binary formats.
 */
export function detectFileKind(bytes: Uint8Array): FileKind | null {
  if (startsWithBytes(bytes, PNG_SIGNATURE)) return "png";
  if (startsWithBytes(bytes, JPEG_SIGNATURE)) return "jpeg";
  const head = Buffer.from(bytes.subarray(0, 1024)).toString("latin1");
  if (head.includes(PDF_SIGNATURE)) return "pdf";
  return null;
}

/**
 * Is this the start of a markup document (SVG, XML, HTML)? Used only to make the
 * refusal of an SVG deliberate and testable rather than incidental.
 */
export function looksLikeMarkup(bytes: Uint8Array): boolean {
  const head = Buffer.from(bytes.subarray(0, 512)).toString("latin1").trimStart().toLowerCase();
  return (
    head.startsWith("<?xml") ||
    head.startsWith("<svg") ||
    head.startsWith("<!doctype") ||
    head.startsWith("<html") ||
    head.includes("<svg")
  );
}

/* -------------------------------------------------------------- filenames */

/**
 * The person's own filename, reduced to something safe to SHOW.
 *
 * It keeps only the last path segment and drops control characters, angle
 * brackets and the characters Windows refuses. The result is never used as a
 * path, a URL or a header value — the stored name is generated by `newFilename`
 * below — so this is a display label, nothing more.
 */
export function displayName(raw: string): string {
  const base = String(raw ?? "").split(/[\\/]/).pop() ?? "";
  const cleaned = base
    // eslint-disable-next-line no-control-regex -- control characters are exactly what must go
    .replace(/[\u0000-\u001f\u007f<>:"|?*]/g, "")
    .trim()
    .slice(0, 120);
  return cleaned || "dokument";
}

/** The name we store under: ours, random, with the extension of the type we detected. */
export function newFilename(kind: FileKind): string {
  return `${randomUUID()}.${FILE_KINDS[kind].extension}`;
}

/* ------------------------------------------------------------- re-encoding */

/**
 * Rebuild an image from its pixels.
 *
 * `sharp` strips every metadata block unless asked to keep it (`withMetadata`),
 * so the output carries no EXIF, no GPS, no XMP, no comment and nothing that was
 * appended to the original file. `rotate()` without arguments applies the EXIF
 * orientation to the pixels before that tag disappears, so the picture still
 * looks the way the person took it.
 *
 * Throws if the image cannot be decoded — the caller turns that into a refusal,
 * because a file we cannot rebuild is a file we will not store.
 */
async function rebuildImage(kind: "jpeg" | "png", bytes: Buffer): Promise<Buffer> {
  const { default: sharp } = await import("sharp");
  const pipeline = sharp(bytes, {
    // A deliberately small ceiling: a decompression bomb is not a letter.
    limitInputPixels: 40_000_000,
    failOn: "error",
  }).rotate();

  const output =
    kind === "jpeg"
      ? await pipeline.jpeg({ quality: 82, mozjpeg: false }).toBuffer()
      : await pipeline.png({ compressionLevel: 9 }).toBuffer();

  if (output.length === 0) throw new Error("empty re-encode");
  // The rebuilt file must still be the format we detected, and must still be a
  // file of the same kind. Belt and braces: a re-encode is not a place to trust.
  if (detectFileKind(output) !== kind) throw new Error("re-encode changed the format");
  return output;
}

/* --------------------------------------------------------------- the gate */

/**
 * Judge one submission. Nothing is written until this returns `ok`.
 *
 * Every refusal is a code, and every code is checked in the order a person would
 * want to hear it: too many files, then a file too big, then a type we cannot
 * take, then a file we could not read.
 */
export async function prepareDocuments(
  incoming: readonly IncomingFile[],
): Promise<PrepareResult> {
  if (incoming.length > MAX_FILES) return { ok: false, code: "too_many" };

  const prepared: PreparedFile[] = [];
  let total = 0;

  for (const file of incoming) {
    const base64 = String(file.contentBase64 ?? "");

    /*
     * A cheap length check BEFORE decoding: base64 is 4 characters for every 3
     * bytes, so a string that is obviously over the cap is refused without ever
     * allocating the decoded buffer. `+ 8` covers padding and whitespace.
     */
    if (base64.length > Math.ceil(MAX_FILE_BYTES / 3) * 4 + 8) {
      return { ok: false, code: "too_large" };
    }

    let bytes: Buffer;
    try {
      bytes = Buffer.from(base64, "base64");
    } catch {
      return { ok: false, code: "unreadable" };
    }
    if (bytes.length === 0) return { ok: false, code: "unreadable" };

    // THE REAL SIZE, measured after decoding — never the number the browser sent.
    if (bytes.length > MAX_FILE_BYTES) return { ok: false, code: "too_large" };
    total += bytes.length;
    if (total > MAX_TOTAL_BYTES) return { ok: false, code: "total_too_large" };

    // THE DECISION, from the first bytes of the file.
    const kind = detectFileKind(bytes);
    if (!kind) return { ok: false, code: "type" };

    let stored = bytes;
    let reencoded = false;

    if (kind === "pdf") {
      /*
       * A PDF is not rewritten. It must at least be a whole document: the header
       * was found above, and a real PDF ends with `%%EOF` within the last
       * kilobyte. Anything else is a fragment, not a letter.
       */
      const tail = bytes.subarray(Math.max(0, bytes.length - 1024)).toString("latin1");
      if (!tail.includes("%%EOF")) return { ok: false, code: "unreadable" };
    } else {
      try {
        stored = await rebuildImage(kind, bytes);
      } catch {
        // Fail closed: no re-encode, no storage.
        return { ok: false, code: "unreadable" };
      }
      reencoded = true;
      // A rebuilt image can in principle grow; it is still bound by the same cap.
      if (stored.length > MAX_FILE_BYTES) return { ok: false, code: "too_large" };
    }

    prepared.push({
      filename: newFilename(kind),
      originalName: displayName(file.filename),
      mimeType: FILE_KINDS[kind].mimeType,
      size: stored.length,
      contentBase64: stored.toString("base64"),
      kind,
      reencoded,
    });
  }

  return { ok: true, documents: prepared };
}

/* ------------------------------------------------------------ serving them */

/**
 * The headers a stored document is served with. Written here, next to the
 * decision about what the file is, so the two can never drift apart.
 *
 *   - `Content-Type` is the type WE decided from the bytes — not the one the file
 *     was uploaded with, and not one derived from its name.
 *   - `Content-Disposition: attachment` with OUR generated filename: the browser
 *     downloads the file, it never renders it in place. A stored HTML or SVG
 *     document therefore cannot run in our origin — and neither can be stored.
 *   - `X-Content-Type-Options: nosniff`: the browser must not second-guess the
 *     type above.
 *   - `Cache-Control: no-store`: a person's document is not cached by a proxy or
 *     left behind in a shared browser profile.
 */
export function documentResponseHeaders(document: {
  filename: string;
  mimeType: string;
}): Record<string, string> {
  const safeName = /^[A-Za-z0-9._-]+$/.test(document.filename)
    ? document.filename
    : "dokument";
  return {
    "Content-Type": document.mimeType,
    "Content-Disposition": `attachment; filename="${safeName}"`,
    "X-Content-Type-Options": "nosniff",
    "Cache-Control": "no-store",
  };
}

/*
 * THE HONEST LIMIT, written down where the code lives:
 *
 *   - There is no separate quarantine container. This is one application, and a
 *     file is decided before it is stored, not opened somewhere else first.
 *   - A PDF is not sanitised internally. A PDF can carry JavaScript and embedded
 *     files; we store it as it arrived and only ever hand it back as a download
 *     with a pinned type. Reading it (capability 1) will need a provider whose
 *     parser is the one taking that risk, and that decision is not made yet.
 *   - Re-encoding proves the pixels, not the innocence of the picture.
 */
